/* eslint-disable security/detect-non-literal-fs-filename -- Only fixed, repository-owned paths are read or written. */
/**
 * Writes everything the homepage shows about Ferrugo's behavior:
 *
 * - app/data/previews/*.png, real renders of a committed fixture;
 * - app/data/home-samples.json, the facts and outcomes beside them.
 *
 * Both come from homepage/samples, a small program that depends on the
 * published ferrugo-thumbnail and ferrugo-native crates from crates.io at the
 * exact version pinned in homepage/samples/Cargo.toml. The inputs are the
 * repository's own fixtures; the JSON records each input's SHA-256.
 *
 * `pnpm sample:write` writes both. `pnpm sample:check` renders again and
 * fails when the JSON no longer matches, or when a committed preview differs
 * from the new render by more than the repository's visual-diff thresholds.
 * Nobody edits these files by hand.
 */
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { format } from "oxfmt";

const root = fileURLToPath(new URL("../../", import.meta.url));
const check = process.argv.includes("--check");
const destination = new URL("../app/data/home-samples.json", import.meta.url);
const previews = fileURLToPath(new URL("../app/data/previews/", import.meta.url));
const repository = (path) => new URL(`../../${path}`, import.meta.url);

const manifest = await readFile(new URL("../samples/Cargo.toml", import.meta.url), "utf8");
const pinned = /^ferrugo-thumbnail = "=([^"]+)"$/m.exec(manifest)?.[1];
const pinnedNative = /^ferrugo-native = "=([^"]+)"$/m.exec(manifest)?.[1];
assert(pinned, "homepage/samples/Cargo.toml must pin ferrugo-thumbnail to one exact version.");
assert.equal(pinnedNative, pinned, "Pin ferrugo-thumbnail and ferrugo-native to the same release.");
const releases = JSON.parse(await readFile(repository(".release-please-manifest.json"), "utf8"));
const release = releases["crates/ferrugo-thumbnail"];
if (!check && pinned !== release) {
  console.warn(
    `Rendering with ferrugo ${pinned}; the current release is ${release}. Update the pins in homepage/samples/Cargo.toml once ${release} is on crates.io.`,
  );
}

const output = execFileSync(
  "cargo",
  [
    "run",
    "--release",
    "--locked",
    "--quiet",
    "--manifest-path",
    "homepage/samples/Cargo.toml",
    "--target-dir",
    "target/homepage-samples",
    "--",
    ...(check ? ["--check"] : []),
    previews,
  ],
  { cwd: root, encoding: "utf8" },
);
const specimens = JSON.parse(output.replaceAll("\r\n", "\n"));
assert.equal(specimens.ferrugo, pinned, "The samples program linked a different Ferrugo.");

// The page's claims about these results, checked here so a new release that
// changes them fails loudly instead of leaving the copy behind.
const outcome = (id) => specimens.outcomes.find((entry) => entry.id === id);
assert.equal(outcome("patent")?.default.rendered, true, "The scanned patent should render.");
assert.equal(
  outcome("patent")?.lowMemory.bucket,
  "renderer.memory-budget",
  "The low-memory profile should refuse the full-size patent preview.",
);
assert.equal(
  outcome("huge-image")?.default.bucket,
  "renderer.memory-budget",
  "The oversized image should hit the memory budget.",
);
// The outcomes chapter counts the public documents that do not preview yet.
assert.equal(outcome("chrome-print")?.default.class, "unsupported");
assert.equal(outcome("data-brief")?.default.class, "malformed");
assert.equal(outcome("tax-form")?.default.class, "malformed");
const [small, large] = specimens.preview.renders;
assert(small?.lowMemory.rendered === true, "The small preview should fit the low-memory budget.");
assert(
  large?.lowMemory.rendered === false,
  "The large preview should exceed the low-memory budget.",
);

/** SHA-256 of every input, so the page names exactly what was rendered. */
const inputs = {};
for (const input of [specimens.preview.input, ...specimens.outcomes.map((entry) => entry.input)]) {
  const bytes = await readFile(repository(input));
  inputs[input] = createHash("sha256").update(bytes).digest("hex");
}

const samples = {
  note: "Generated by homepage/scripts/render-home-samples.mjs. Do not edit.",
  renderedWith: { ferrugo: pinned, source: "crates.io" },
  inputs,
  ...specimens,
};
const formatted = await format("home-samples.json", JSON.stringify(samples));
assert.equal(formatted.errors.length, 0);
if (check) {
  const text = await readFile(destination, "utf8");
  const committed = text.replaceAll("\r\n", "\n");
  assert.equal(
    committed,
    formatted.code,
    "The homepage samples changed. Run pnpm sample:write and commit the result.",
  );
  console.log(`The homepage samples match ferrugo ${pinned} from crates.io.`);
} else {
  await writeFile(destination, formatted.code);
  console.log(`Wrote app/data/home-samples.json and the previews with ferrugo ${pinned}.`);
}
